#!/usr/bin/env python3
"""Generate SUMMARY.md and the landing pages (tracks, labs) for one language.

English is the source of truth. A translated book is assembled into .build/<lang>/src
first, then this script runs with --src pointing at that copy. Sentences and track names
come from the language's strings.json; chapter titles come from each page's meta block
(translated when an overlay page exists, English otherwise).
"""
import argparse
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
EN_STRINGS = os.path.join(ROOT, 'mdbook', 'i18n', 'strings.en.json')

def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument('--lang', default='en')
    p.add_argument('--src', default=os.path.join(ROOT, 'mdbook', 'src'))
    p.add_argument('--out', default=None, help='defaults to --src')
    p.add_argument('--strings', default=None)
    return p.parse_args()

def load_strings(args):
    path = args.strings or (EN_STRINGS if args.lang == 'en'
                            else os.path.join(ROOT, 'mdbook', 'i18n', args.lang, 'strings.json'))
    with open(path, encoding='utf-8') as f:
        own = json.load(f)
    if args.lang == 'en':
        return own
    # Missing keys fall back to English, just like the book's pages do.
    with open(EN_STRINGS, encoding='utf-8') as f:
        base = json.load(f)
    def merge(a, b):
        if not isinstance(a, dict) or not isinstance(b, dict):
            return b
        out = dict(a)
        for k, v in b.items():
            out[k] = merge(a.get(k), v)
        return out
    return merge(base, own)

def title_from(path, fallback=None):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    m = re.search(r'^title:\s*(.+)$', text, re.M)
    if m:
        return m.group(1).strip()
    m = re.search(r'^# (.+)$', text, re.M)
    return m.group(1).strip() if m else fallback

def main():
    args = parse_args()
    src = os.path.abspath(args.src)
    out = os.path.abspath(args.out or args.src)
    strings = load_strings(args)
    summary = strings.get('summary', {})
    labs_strings = strings.get('labs', {})
    tracks = summary.get('tracks', {})

    lines = ['# ' + summary.get('title', 'Summary'), '',
             '- [' + summary.get('home', 'Capital-First Trading') + '](index.md)']

    track_dirs = sorted(
        d for d in os.listdir(src)
        if os.path.isdir(os.path.join(src, d)) and re.match(r'\d\d-', d)
    )
    for tdir in track_dirs:
        name = tracks.get(tdir, tdir)
        chapters = []
        for idx in sorted(glob.glob(os.path.join(src, tdir, '*', 'index.md'))):
            chapters.append((title_from(idx), os.path.relpath(idx, src)))
        page = ['<!-- generated by tools/build/gen_summary.py; do not edit -->', '# ' + name, '']
        page += [f'{n}. [{ti}]({os.path.relpath(p, tdir)})' for n, (ti, p) in enumerate(chapters, 1)]
        page_path = os.path.join(src, tdir, 'index.md')
        os.makedirs(os.path.dirname(page_path), exist_ok=True)
        with open(page_path, 'w', encoding='utf-8') as f:
            f.write('\n'.join(page) + '\n')
        lines.append(f'- [{name}]({tdir}/index.md)')
        lines += [f'  - [{ti}]({p})' for ti, p in chapters]

    lab_files = sorted(glob.glob(os.path.join(src, 'labs', '*.md')))
    lab_files = [f for f in lab_files if os.path.basename(f) != 'index.md']
    if lab_files:
        tools = labs_strings.get('tools', {})
        entries = []
        for f in lab_files:
            base = os.path.basename(f)
            entries.append((tools.get(base) or title_from(f), base))
        page = ['<!-- generated by tools/build/gen_summary.py; do not edit -->',
                '# ' + labs_strings.get('title', 'Labs'), '',
                labs_strings.get('intro', 'Tools you can use while you study. Everything runs on your device.'), '']
        page += [f'{n}. [{t}]({f})' for n, (t, f) in enumerate(entries, 1)]
        upcoming = labs_strings.get('upcoming', [])
        if upcoming:
            page += ['', '## ' + labs_strings.get('comingSoonTitle', 'Coming soon'), '',
                     labs_strings.get('comingSoonIntro', ''), '']
            page += [f"- **{x['title']}.** {x['description']}" for x in upcoming]
        with open(os.path.join(src, 'labs', 'index.md'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(page) + '\n')
        lines.append('- [' + labs_strings.get('title', 'Labs') + '](labs/index.md)')
        lines += [f'  - [{t}](labs/{f})' for t, f in entries]

    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'SUMMARY.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'SUMMARY.md written for {args.lang}')

if __name__ == '__main__':
    main()
