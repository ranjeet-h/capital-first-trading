#!/usr/bin/env python3
"""Generate mdbook/src/SUMMARY.md from the chapter folders (meta comment holds id + title)."""
import glob, os, re
SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'mdbook', 'src')
TRACKS = {
 '00-start-here': '0. Start here',
 '01-market-foundations': '1. Market foundations',
 '02-money-and-math': '2. Money and math',
 '03-chart-reading': '3. Chart reading',
 '04-kite-and-execution': '4. Kite and execution (demo only)',
 '05-indicators': '5. Indicators',
 '06-strategy': '6. Strategy',
 '07-testing-and-validation': '7. Testing and validation',
 '08-psychology-and-journaling': '8. Psychology and journaling',
 '09-advanced': '9. Advanced (theory only)',
 '10-graduation-gates': '10. Graduation gates',
}
out = ['# Summary', '', '- [Capital-First Trading](index.md)']
for tdir in sorted(d for d in os.listdir(SRC) if os.path.isdir(os.path.join(SRC, d)) and re.match(r'\d\d-', d)):
    name = TRACKS.get(tdir, tdir)
    chapters = []
    for idx in sorted(glob.glob(os.path.join(SRC, tdir, '*', 'index.md'))):
        t = open(idx).read()
        title = re.search(r'^title:\s*(.+)$', t, re.M).group(1).strip()
        chapters.append((title, os.path.relpath(idx, SRC)))
    # generated track landing page
    page = ['<!-- generated by tools/build/gen_summary.py; do not edit -->', '# ' + name, '']
    page += [f'{n}. [{ti}]({os.path.relpath(p, tdir)})' for n, (ti, p) in enumerate(chapters, 1)]
    open(os.path.join(SRC, tdir, 'index.md'), 'w').write('\n'.join(page) + '\n')
    out.append(f'- [{name}]({tdir}/index.md)')
    out += [f'  - [{ti}]({p})' for ti, p in chapters]
open(os.path.join(SRC, 'SUMMARY.md'), 'w').write('\n'.join(out) + '\n')
print('SUMMARY.md written')
