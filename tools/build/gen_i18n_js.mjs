// Compiles mdbook/i18n/strings.<lang>.json into the theme/i18n.js file that the
// shared theme scripts read. One file per built book: no runtime fetch, because the
// book must work offline and because a page can fall back to English while the
// book's <html lang> is Marathi.
//
// Usage:
//   node tools/build/gen_i18n_js.mjs --lang en --out mdbook/theme/i18n.js
//   node tools/build/gen_i18n_js.mjs --lang mr --out .build/mr/theme/i18n.js --site combined
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const I18N = join(ROOT, "mdbook", "i18n");
const EN_FILE = join(I18N, "strings.en.json");

export function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

export function deepMerge(base, override) {
  if (Array.isArray(base) || Array.isArray(override)) return override ?? base;
  if (base && override && typeof base === "object" && typeof override === "object") {
    const out = { ...base };
    for (const [k, v] of Object.entries(override)) out[k] = deepMerge(base[k], v);
    return out;
  }
  return override === undefined ? base : override;
}

export function languageFile(code) {
  return code === "en" ? EN_FILE : join(I18N, code, "strings.json");
}

export function languageCodes() {
  const codes = new Set(["en"]);
  for (const entry of readdirSync(I18N, { withFileTypes: true })) {
    if (entry.isDirectory() && existsSync(join(I18N, entry.name, "strings.json"))) codes.add(entry.name);
  }
  return [...codes].sort((a, b) => (a === "en" ? -1 : b === "en" ? 1 : a.localeCompare(b)));
}

export function loadStrings(code) {
  const own = readJson(languageFile(code));
  const merged = code === "en" ? own : deepMerge(readJson(EN_FILE), own);
  const meta = merged.meta || {};
  const language = meta.language || code;
  const root = meta.root ?? (language === "en" ? "" : `${language}/`);
  return { ...merged, meta: { ...meta, language, root } };
}

export function languageList(except) {
  return languageCodes()
    .filter((code) => code !== except)
    .map((code) => {
      const strings = loadStrings(code);
      return { code, name: strings.meta.name || code, root: strings.meta.root };
    });
}

export function relativeRoot(from, to) {
  const f = from ? from.replace(/\/+$/, "") : ".";
  const t = to ? to.replace(/\/+$/, "") : ".";
  const rel = posix.relative("/site/" + f, "/site/" + t);
  return rel ? rel + "/" : "./";
}

export function compileI18n({ lang, site = "single" }) {
  const strings = loadStrings(lang);
  const english = lang === "en" ? strings : loadStrings("en");
  const other = languageList(strings.meta.language).map((item) => ({
    ...item,
    root: relativeRoot(strings.meta.root, item.root),
  }));
  const data = {
    lang: strings.meta.language,
    name: strings.meta.name,
    root: strings.meta.root,
    showSwitcher: site === "combined",
    other,
    strings,
    // A page can fall back to English while the book itself is Marathi. The shared
    // scripts pick the dictionary from the page's data-page-lang / data-quiz-lang.
    byLang: {
      en: english,
      [strings.meta.language]: strings,
    },
  };
  return `// Generated by tools/build/gen_i18n_js.mjs. Do not edit.
window.CFT_I18N = ${JSON.stringify(data, null, 2)};
window.CFT_T = function (key, vars, lang) {
  var data = window.CFT_I18N || {};
  var code = lang || data.lang || "en";
  var value = (data.byLang && data.byLang[code]) || data.strings || {};
  var parts = String(key).split(".");
  for (var i = 0; i < parts.length; i++) {
    if (value == null) break;
    // strings.json keeps some keys flat, such as "quiz.title" inside "ui". Prefer the
    // longest remaining key so both flat and nested layouts work.
    var rest = parts.slice(i).join(".");
    if (typeof value === "object" && Object.prototype.hasOwnProperty.call(value, rest)) {
      value = value[rest];
      break;
    }
    value = value[parts[i]];
  }
  if (typeof value !== "string") value = key;
  if (!vars) return value;
  return value.replace(/\\{([a-zA-Z0-9_]+)\\}/g, function (all, name) {
    return Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : all;
  });
};
`;
}

function parseArgs(argv) {
  const args = { lang: "en", out: null, site: "single" };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--lang") args.lang = argv[++i];
    else if (a === "--out") args.out = argv[++i];
    else if (a === "--site") args.site = argv[++i];
    else if (a.startsWith("--")) throw new Error(`Unknown argument ${a}`);
  }
  if (!args.out) args.out = join(ROOT, "mdbook", "theme", "i18n.js");
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const js = compileI18n(args);
  mkdirSync(dirname(resolve(args.out)), { recursive: true });
  writeFileSync(resolve(args.out), js);
  console.log(`i18n.js written for ${args.lang} (${args.site}) -> ${args.out}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
