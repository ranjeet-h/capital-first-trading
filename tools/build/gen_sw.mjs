// After mdBook runs: write book/sw.js with the list of every file, so the whole book is
// cached for offline use. One cache per language so the English and Marathi books cannot
// overwrite each other.
//
// Usage:
//   node tools/build/gen_sw.mjs --root mdbook/book --lang en
//   node tools/build/gen_sw.mjs --root .pages-build/mr --lang mr
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";

/** @param {string} root @param {{exclude?: string[]}} [opts] @returns {string[]} */
export function fileList(root, { exclude = [] } = {}) {
  const files = [];
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else files.push(relative(root, p).split(sep).join("/"));
    }
  };
  walk(root);
  return files
    .filter((f) => f !== "sw.js" && !f.endsWith(".map") && !f.startsWith("print"))
    .filter((f) => !exclude.some((prefix) => {
      const clean = prefix.replace(/\/$/, "");
      return f === clean || f.startsWith(clean + "/");
    }))
    .sort();
}

export function cacheVersion(root, urls) {
  const h = createHash("sha256");
  for (const u of urls) {
    h.update(u);
    h.update(readFileSync(join(root, u)));
  }
  return h.digest("hex").slice(0, 12);
}

export function workerSource({ version, urls, lang, exclude = "" }) {
  const cleanExclude = exclude ? exclude.replace(/^\/+|\/+$/g, "") + "/" : "";
  return `// Generated by tools/build/gen_sw.mjs. Do not edit.
const LANG = ${JSON.stringify(lang)};
const PREFIX = "cft-" + LANG + "-";
const CACHE = PREFIX + ${JSON.stringify(version)};
const EXCLUDE = ${JSON.stringify(cleanExclude)};
const FILES = ${JSON.stringify(["./", ...urls])};
const OLD_UNPREFIXED = /^cft-[0-9a-f]{12}$/;
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.map((k) => {
    if (k === CACHE) return null;
    if (k.startsWith(PREFIX)) return caches.delete(k);
    // One-time cleanup of the old, unprefixed English cache. The Marathi worker
    // leaves it alone; the English worker removes it when it next updates.
    if (LANG === "en" && OLD_UNPREFIXED.test(k)) return caches.delete(k);
    return null;
  }))).then(() => self.clients.claim()));
});
function excluded(url) {
  if (!EXCLUDE) return false;
  return url.href.startsWith(new URL(EXCLUDE, self.registration.scope).href);
}
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  if (excluded(url)) return;
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => {
    if (!res || res.status !== 200 || res.type === "opaque") return res;
    const copy = res.clone();
    caches.open(CACHE).then((c) => c.put(req, copy));
    return res;
  }).catch(() => caches.match("./"))));
});
`;
}

function parseArgs(argv) {
  const args = { root: "mdbook/book", lang: "en", exclude: "" };
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--root") args.root = argv[++i];
    else if (a === "--lang") args.lang = argv[++i];
    else if (a === "--exclude") args.exclude = argv[++i];
    else if (a.startsWith("--")) throw new Error(`Unknown argument ${a}`);
    else rest.push(a);
  }
  // Backwards-compatible positional form: node gen_sw.mjs [root]
  if (rest[0]) args.root = rest[0];
  if (!args.exclude && args.lang === "en") args.exclude = "mr";
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const root = resolve(args.root);
  const urls = fileList(root, { exclude: args.exclude ? [args.exclude] : [] });
  const version = cacheVersion(root, urls);
  writeFileSync(join(root, "sw.js"), workerSource({ version, urls, lang: args.lang, exclude: args.exclude }));
  console.log(`sw.js written for ${args.lang}: ${urls.length} files, cache cft-${args.lang}-${version}`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) main();
