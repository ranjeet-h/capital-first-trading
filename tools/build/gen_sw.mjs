// After mdBook runs: write book/sw.js with the list of every file, so the whole book is cached for offline use.
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const root = process.argv[2] ?? "mdbook/book";
const files = [];
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); statSync(p).isDirectory() ? walk(p) : files.push(p); } };
walk(root);
const urls = files.map((f) => relative(root, f)).filter((f) => f !== "sw.js" && !f.endsWith(".map") && !f.startsWith("print") ).sort();
const h = createHash("sha256");
for (const u of urls) { h.update(u); h.update(readFileSync(join(root, u))); }
const version = h.digest("hex").slice(0, 12);

writeFileSync(join(root, "sw.js"), `// Generated by tools/build/gen_sw.mjs. Do not edit.
const CACHE = "cft-${version}";
const FILES = ${JSON.stringify(["./", ...urls])};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("cft-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`);
console.log("sw.js: " + urls.length + " files, version " + version);
